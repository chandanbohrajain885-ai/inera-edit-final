import { seededRandom } from './utils.js';

export const MOODS = {
  cinematic: { label: 'Cinematic', bpm: 92, key: 50, minor: true, names: ['Horizon Lines', 'Northern Glass', 'Long Exposure', 'Quiet Summit'] },
  energetic: { label: 'Energetic', bpm: 124, key: 45, minor: true, names: ['Neon Drive', 'Pulse Runner', 'Velocity', 'Afterburn'] },
  upbeat: { label: 'Upbeat', bpm: 116, key: 48, minor: false, names: ['Golden Hour', 'Bright Side', 'Confetti Sky', 'Good Day'] },
  calm: { label: 'Calm', bpm: 74, key: 53, minor: false, names: ['Still Water', 'Morning Tea', 'Soft Focus', 'Drift'] },
  subtle: { label: 'Subtle Background', bpm: 90, key: 52, minor: false, names: ['Desk Light', 'Paper Notes', 'Low Hum', 'Clear Mind'] },
};

const PROG_MINOR = [[0, 3, 7], [8, 12, 15], [3, 7, 10], [10, 14, 17]]; // i VI III VII
const PROG_MINOR_B = [[0, 3, 7], [5, 8, 12], [8, 12, 15], [7, 11, 14]]; // i iv VI V
const PROG_MAJOR = [[0, 4, 7], [7, 11, 14], [9, 12, 16], [5, 9, 12]]; // I V vi IV
const PROG_MAJOR_B = [[0, 4, 7, 11], [9, 12, 16, 19], [5, 9, 12, 16], [7, 11, 14, 17]]; // Imaj7 vi7 IVmaj7 V

const mtof = (m) => 440 * Math.pow(2, (m - 69) / 12);

function makeImpulse(ctx, seconds, decay, rnd) {
  const len = Math.floor(ctx.sampleRate * seconds);
  const buf = ctx.createBuffer(2, len, ctx.sampleRate);
  for (let c = 0; c < 2; c++) {
    const d = buf.getChannelData(c);
    for (let i = 0; i < len; i++) d[i] = (rnd() * 2 - 1) * Math.pow(1 - i / len, decay);
  }
  return buf;
}
function makeNoise(ctx, seconds, rnd) {
  const len = Math.floor(ctx.sampleRate * seconds);
  const buf = ctx.createBuffer(1, len, ctx.sampleRate);
  const d = buf.getChannelData(0);
  for (let i = 0; i < len; i++) d[i] = rnd() * 2 - 1;
  return buf;
}

export function trackInfo(mood, seed) {
  const m = MOODS[mood] || MOODS.cinematic;
  const name = m.names[Math.abs(seed) % m.names.length];
  return {
    mood, bpm: m.bpm, title: `Inera Original — ${name}`,
    license: 'Original composition generated by Inera Edit Flow on your device. Royalty-free; commercial use allowed; no attribution required.',
  };
}

// Generate a stereo AudioBuffer of exactly `duration` seconds.
// loopBars: render a seamless loop of exactly loopBars bars plus a release tail (for long videos).
export async function generateMusic({ mood = 'cinematic', duration = 30, seed = 1, sampleRate = 44100, energy = 1, loopBars = 0, tail = 4 }) {
  const m0 = MOODS[mood] || MOODS.cinematic;
  const loopLen = loopBars ? loopBars * (240 / m0.bpm) : 0;
  if (loopBars) duration = loopLen + tail;
  const m = MOODS[mood] || MOODS.cinematic;
  const rnd = seededRandom(seed * 7919 + 13);
  const bpm = m.bpm;
  const beat = 60 / bpm;
  const bar = beat * 4;
  const len = Math.ceil(duration * sampleRate);
  const ctx = new OfflineAudioContext(2, len, sampleRate);
  const keyShift = [0, 2, -2, 5, -3][seed % 5];
  const root = m.key + keyShift;
  const prog = m.minor ? (seed % 2 ? PROG_MINOR_B : PROG_MINOR) : (seed % 2 ? PROG_MAJOR_B : PROG_MAJOR);
  const noise = makeNoise(ctx, 1, rnd);

  const master = ctx.createGain(); master.gain.value = 0.9;
  const comp = ctx.createDynamicsCompressor();
  comp.threshold.value = -16; comp.ratio.value = 3.5; comp.attack.value = 0.01; comp.release.value = 0.2;
  master.connect(comp); comp.connect(ctx.destination);
  const reverb = ctx.createConvolver(); reverb.buffer = makeImpulse(ctx, mood === 'calm' || mood === 'cinematic' ? 3.2 : 1.8, 3, rnd);
  const revGain = ctx.createGain(); revGain.gain.value = mood === 'energetic' ? 0.18 : 0.32;
  reverb.connect(revGain); revGain.connect(master);
  const bus = (g, rev = 0) => { const n = ctx.createGain(); n.gain.value = g; n.connect(master); if (rev) { const s = ctx.createGain(); s.gain.value = rev; n.connect(s); s.connect(reverb); } return n; };

  const drumsBus = bus(energy * (mood === 'calm' ? 0 : mood === 'subtle' ? 0.45 : mood === 'cinematic' ? 0.7 : 0.9), 0.05);
  const bassBus = bus(0.55 * energy);
  const padBus = bus(mood === 'energetic' ? 0.16 : 0.24, 0.6);
  const leadBus = bus(mood === 'subtle' ? 0.11 : 0.15, 0.45);

  const kick = (t, v = 1) => {
    const o = ctx.createOscillator(), g = ctx.createGain();
    o.frequency.setValueAtTime(140, t); o.frequency.exponentialRampToValueAtTime(42, t + 0.12);
    g.gain.setValueAtTime(0.0001, t); g.gain.exponentialRampToValueAtTime(v, t + 0.005); g.gain.exponentialRampToValueAtTime(0.001, t + 0.35);
    o.connect(g); g.connect(drumsBus); o.start(t); o.stop(t + 0.4);
  };
  const noiseHit = (t, dur, type, freq, v, q = 0.8) => {
    const s = ctx.createBufferSource(); s.buffer = noise; s.playbackRate.value = 0.8 + rnd() * 0.4;
    const f = ctx.createBiquadFilter(); f.type = type; f.frequency.value = freq; f.Q.value = q;
    const g = ctx.createGain(); g.gain.setValueAtTime(v, t); g.gain.exponentialRampToValueAtTime(0.001, t + dur);
    s.connect(f); f.connect(g); g.connect(drumsBus); s.start(t, rnd() * 0.5); s.stop(t + dur + 0.02);
  };
  const snare = (t, v = 0.5) => {
    noiseHit(t, 0.2, 'bandpass', 1800, v, 0.7);
    const o = ctx.createOscillator(), g = ctx.createGain(); o.type = 'triangle'; o.frequency.value = 190;
    g.gain.setValueAtTime(v * 0.6, t); g.gain.exponentialRampToValueAtTime(0.001, t + 0.12);
    o.connect(g); g.connect(drumsBus); o.start(t); o.stop(t + 0.15);
  };
  const hat = (t, v = 0.14, open = false) => noiseHit(t, open ? 0.18 : 0.045, 'highpass', 8000, v, 0.5);
  const synthNote = (dest, t, dur, midi, { type = 'sawtooth', v = 0.2, a = 0.01, r = 0.2, cutoff = 2400, detune = 0, voices = 1 } = {}) => {
    const g = ctx.createGain();
    const f = ctx.createBiquadFilter(); f.type = 'lowpass'; f.frequency.value = cutoff; f.Q.value = 0.7;
    g.gain.setValueAtTime(0.0001, t); g.gain.linearRampToValueAtTime(v, t + a);
    g.gain.setValueAtTime(v, Math.max(t + a, t + dur - r)); g.gain.linearRampToValueAtTime(0.0001, t + dur);
    f.connect(g); g.connect(dest);
    for (let k = 0; k < voices; k++) {
      const o = ctx.createOscillator(); o.type = type; o.frequency.value = mtof(midi);
      o.detune.value = voices > 1 ? (k - (voices - 1) / 2) * detune : 0;
      o.connect(f); o.start(t); o.stop(t + dur + 0.05);
    }
  };

  const bars = loopBars || Math.ceil(duration / bar) + 1;
  const introBars = loopBars ? 0 : duration > bar * 4 ? 1 : 0;
  const outroStart = loopBars ? Infinity : duration - Math.min(bar * 2, duration * 0.15);
  for (let b = 0; b < bars; b++) {
    const t0 = b * bar;
    if (t0 > duration) break;
    const chord = prog[b % prog.length];
    const inIntro = b < introBars;
    const inOutro = t0 >= outroStart;
    // Pads
    const padDur = bar + 0.05;
    for (const n of chord) synthNote(padBus, t0, padDur, root + 12 + n, { type: mood === 'calm' || mood === 'subtle' ? 'triangle' : 'sawtooth', v: 0.07, a: mood === 'energetic' ? 0.05 : 0.6, r: 0.5, cutoff: mood === 'cinematic' ? 1400 : 1900, detune: 9, voices: 2 });
    // Bass
    if (!inIntro) {
      const bassMidi = root - 12 + chord[0];
      if (mood === 'energetic') {
        for (let e = 0; e < 8; e++) synthNote(bassBus, t0 + e * beat / 2, beat / 2 - 0.02, bassMidi + (e % 4 === 3 ? 12 : 0), { type: 'sawtooth', v: 0.22, a: 0.005, r: 0.05, cutoff: 600 });
      } else if (mood === 'upbeat') {
        for (let e = 0; e < 4; e++) synthNote(bassBus, t0 + e * beat, beat * 0.6, bassMidi + (e === 2 ? 7 : 0), { type: 'square', v: 0.14, a: 0.005, r: 0.08, cutoff: 700 });
      } else {
        synthNote(bassBus, t0, bar * 0.98, bassMidi, { type: 'triangle', v: 0.25, a: 0.08, r: 0.4, cutoff: 500 });
      }
    }
    // Lead / arpeggio
    const arpSteps = mood === 'energetic' ? 8 : mood === 'upbeat' ? 8 : mood === 'cinematic' ? 4 : mood === 'subtle' ? 4 : 2;
    if (!inIntro || mood === 'calm' || mood === 'cinematic') {
      for (let e = 0; e < arpSteps; e++) {
        if (mood === 'subtle' && rnd() < 0.35) continue;
        const note = chord[(e + (b % 2)) % chord.length] + (e % arpSteps >= arpSteps / 2 ? 12 : 0);
        const st = t0 + e * (bar / arpSteps);
        synthNote(leadBus, st, bar / arpSteps * 0.9, root + 24 + note, { type: mood === 'energetic' ? 'square' : 'triangle', v: mood === 'energetic' ? 0.06 : 0.09, a: 0.005, r: 0.12, cutoff: mood === 'energetic' ? 3200 : 2600 });
      }
    }
    // Drums
    if (!inIntro && !inOutro && mood !== 'calm') {
      for (let q = 0; q < 4; q++) {
        const bt = t0 + q * beat;
        if (mood === 'energetic') { kick(bt, 0.95); hat(bt + beat / 2, 0.16, q === 3); if (q % 2 === 1) snare(bt, 0.45); hat(bt, 0.07); }
        else if (mood === 'upbeat') { if (q === 0 || q === 2) kick(bt, 0.85); if (q % 2 === 1) snare(bt, 0.42); hat(bt + beat / 2, 0.12); hat(bt, 0.06); }
        else if (mood === 'cinematic') { if (q === 0) kick(bt, 0.9); if (q === 2) snare(bt, 0.32); if (b % 2 === 1 && q === 3) kick(bt + beat / 2, 0.6); }
        else if (mood === 'subtle') { if (q === 0 || q === 2) kick(bt, 0.55); if (q === 1 || q === 3) snare(bt, 0.18); hat(bt + beat / 2, 0.05); }
      }
    }
  }
  // Global fade in / out (loops are faded by the mixer instead)
  if (!loopBars) {
    master.gain.setValueAtTime(0.0001, 0);
    master.gain.linearRampToValueAtTime(0.9, Math.min(1.2, duration / 4));
    master.gain.setValueAtTime(0.9, Math.max(0, duration - 1.8));
    master.gain.linearRampToValueAtTime(0.0001, duration);
  }
  const buffer = await ctx.startRendering();
  return { buffer, bpm, beat, loopLen, info: trackInfo(mood, seed) };
}

// Short synthesized sound effects (whoosh, pop, hit) — also original
export async function generateSfx(type, sampleRate = 44100, seed = 3) {
  const rnd = seededRandom(seed);
  const dur = type === 'whoosh' ? 0.6 : type === 'hit' ? 0.9 : 0.15;
  const ctx = new OfflineAudioContext(2, Math.ceil(dur * sampleRate), sampleRate);
  const g = ctx.createGain(); g.connect(ctx.destination);
  if (type === 'whoosh') {
    const s = ctx.createBufferSource(); s.buffer = makeNoise(ctx, dur, rnd);
    const f = ctx.createBiquadFilter(); f.type = 'bandpass'; f.Q.value = 1.4;
    f.frequency.setValueAtTime(300, 0); f.frequency.exponentialRampToValueAtTime(5000, dur * 0.55); f.frequency.exponentialRampToValueAtTime(900, dur);
    g.gain.setValueAtTime(0.0001, 0); g.gain.exponentialRampToValueAtTime(0.5, dur * 0.5); g.gain.exponentialRampToValueAtTime(0.0001, dur);
    s.connect(f); f.connect(g); s.start(0);
  } else if (type === 'hit') {
    const o = ctx.createOscillator(); o.frequency.setValueAtTime(110, 0); o.frequency.exponentialRampToValueAtTime(38, 0.5);
    g.gain.setValueAtTime(0.8, 0); g.gain.exponentialRampToValueAtTime(0.0001, dur);
    o.connect(g); o.start(0); o.stop(dur);
    const s = ctx.createBufferSource(); s.buffer = makeNoise(ctx, dur, rnd);
    const f = ctx.createBiquadFilter(); f.type = 'lowpass'; f.frequency.value = 1200;
    const g2 = ctx.createGain(); g2.gain.setValueAtTime(0.3, 0); g2.gain.exponentialRampToValueAtTime(0.0001, 0.4);
    s.connect(f); f.connect(g2); g2.connect(ctx.destination); s.start(0);
  } else {
    const o = ctx.createOscillator(); o.type = 'sine';
    o.frequency.setValueAtTime(900, 0); o.frequency.exponentialRampToValueAtTime(1600, 0.06);
    g.gain.setValueAtTime(0.0001, 0); g.gain.exponentialRampToValueAtTime(0.35, 0.01); g.gain.exponentialRampToValueAtTime(0.0001, dur);
    o.connect(g); o.start(0); o.stop(dur);
  }
  return ctx.startRendering();
}
